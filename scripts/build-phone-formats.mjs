/**
 * Build src/data/phone-formats.json. For every region it records the calling
 * code and the shape of a local mobile number with its digits as x, like
 * xxxxx xxxxx in India. The editor uses the shape as the phone placeholder,
 * so the format is shown without a number that could belong to someone, and
 * the calling code in the help text about travelling abroad.
 *
 * Reads the metadata in libphonenumber-js, a dev dependency. Run it by hand
 * after updating that package, and commit the output. The app build never
 * runs this, and the app does not ship the library.
 */
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join, dirname } from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const core = require('libphonenumber-js/core');
const metadata = require('libphonenumber-js/metadata.max.json');
const examples = require('libphonenumber-js/mobile/examples');

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = {
  _note: 'ISO 3166-1 alpha-2 to its calling code and the shape of a local mobile number, digits as x. Generated by scripts/build-phone-formats.mjs from libphonenumber-js metadata.',
};
for (const code of core.getCountries(metadata).sort()) {
  const calling = `+${core.getCountryCallingCode(code, metadata)}`;
  const example = core.getExampleNumber(code, examples, metadata);
  // The number as dialled after the calling code, so no trunk prefix is shown.
  out[code] = { calling, local: example ? example.formatInternational().slice(calling.length).trim().replace(/\d/g, 'x') : 'xxxx xxxx' };
}
writeFileSync(join(root, 'src', 'data', 'phone-formats.json'), JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${Object.keys(out).length - 1} regions`);
